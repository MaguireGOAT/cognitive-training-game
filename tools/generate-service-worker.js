const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const outputPath = path.join(root, 'sw.js');
const ignored = new Set([
  'AGENTS.md',
  'sw.js',
  '.git',
  '.gitignore',
  'node_modules',
  'tools',
  'tests',
  'optimization-preview',
  'package.json',
  'package-lock.json'
]);
const assets = [];
const mediaExtensions = new Set(['.webp', '.png', '.mp3']);

function collect(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ignored.has(entry.name)) continue;
    if (entry.isFile() && entry.name.endsWith('.html') && entry.name !== 'index.html') continue;
    const absolute = path.join(dir, entry.name);
    const relative = path.relative(root, absolute).split(path.sep).join('/');
    // Legacy Windows TTS WAVs are no longer referenced by the N-back audio map.
    if (entry.isFile() && relative.startsWith('assets/audio/nback/') && entry.name.endsWith('.wav')) continue;
    if (entry.isDirectory()) {
      collect(absolute);
    } else {
      assets.push(relative);
    }
  }
}

collect(root);
assets.sort();

function toAssetEntry(asset) {
  return {
    path: asset,
    hash: crypto.createHash('sha1')
      .update(fs.readFileSync(path.join(root, asset)))
      .digest('hex')
  };
}

const appAssets = assets.filter(asset => !mediaExtensions.has(path.extname(asset).toLowerCase())).map(toAssetEntry);
const mediaAssets = assets.filter(asset => mediaExtensions.has(path.extname(asset).toLowerCase())).map(toAssetEntry);
const appCacheName = 'cognitive-app-' + Date.now();
const mediaCacheName = 'cognitive-media-v1';
const serviceWorker = `/* Generated by tools/generate-service-worker.js. Do not edit by hand. */
const APP_CACHE_NAME = '${appCacheName}';
const MEDIA_CACHE_NAME = '${mediaCacheName}';
const APP_ASSET_PATHS = ${JSON.stringify(appAssets, null, 2)};
const MEDIA_ASSET_PATHS = ${JSON.stringify(mediaAssets, null, 2)};

importScripts('js/worker-runtime.js');

createCognitiveWorker({
  self,
  appCacheName: APP_CACHE_NAME,
  mediaCacheName: MEDIA_CACHE_NAME,
  assetPaths: APP_ASSET_PATHS,
  mediaAssetPaths: MEDIA_ASSET_PATHS
});
`;

fs.writeFileSync(outputPath, serviceWorker, 'utf8');
console.log('Generated ' + outputPath + ' with ' + assets.length + ' assets (' + mediaAssets.length + ' stable media).');
