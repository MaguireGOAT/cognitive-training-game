const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outputPath = path.join(root, 'sw.js');
const ignored = new Set([
  'sw.js',
  '.git',
  '.gitignore',
  'node_modules',
  'tools',
  'optimization-preview',
  'package.json',
  'package-lock.json'
]);
const assets = [];

function collect(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ignored.has(entry.name)) continue;
    if (entry.isFile() && entry.name.endsWith('.html') && entry.name !== 'index.html') continue;
    const absolute = path.join(dir, entry.name);
    const relative = path.relative(root, absolute).split(path.sep).join('/');
    if (entry.isDirectory()) {
      collect(absolute);
    } else {
      assets.push(relative);
    }
  }
}

collect(root);
assets.sort();

const cacheName = 'cognitive-game-' + Date.now();
const serviceWorker = `/* Generated by tools/generate-service-worker.js. Do not edit by hand. */
const CACHE_NAME = '${cacheName}';
const ASSET_PATHS = ${JSON.stringify(assets, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      await cache.addAll(ASSET_PATHS);
    } catch (error) {
      console.warn('Precache incomplete:', error);
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys
      .filter((key) => key !== CACHE_NAME)
      .map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        const cache = await caches.open(CACHE_NAME);
        cache.put(request, response.clone());
        return response;
      } catch (error) {
        const cached = await caches.match('index.html');
        if (cached) return cached;
        return new Response('Offline', {
          status: 503,
          headers: { 'Content-Type': 'text/plain; charset=utf-8' }
        });
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cached = await caches.match(request);
    if (cached) return cached;
    try {
      const response = await fetch(request);
      if (response.ok) {
        const cache = await caches.open(CACHE_NAME);
        cache.put(request, response.clone());
      }
      return response;
    } catch (error) {
      return new Response('', { status: 408, statusText: 'Offline' });
    }
  })());
});
`;

fs.writeFileSync(outputPath, serviceWorker, 'utf8');
console.log('Generated ' + outputPath + ' with ' + assets.length + ' assets.');
